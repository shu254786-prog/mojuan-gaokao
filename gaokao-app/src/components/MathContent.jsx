import React, { useMemo } from "react";
import katex from "katex";
import "katex/contrib/mhchem";
import { bankUrl } from "../utils/paths";

function escapeHtml(str) {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function renderKatexSafe(tex, displayMode) {
  const cleaned = tex
    .trim()
    .replace(/([^\\])_{2,}/g, "$1\\underline{\\hspace{2.2em}}")
    .replace(/^_{2,}/, "\\underline{\\hspace{2.2em}}");
  try {
    return katex.renderToString(cleaned, {
      displayMode,
      throwOnError: false,
      strict: false,
      trust: true,
    });
  } catch {
    return `<code>${escapeHtml(tex)}</code>`;
  }
}

function renderContentToHtml(raw, inline = false) {
  if (!raw) return "";

  const placeholders = [];
  const hold = (html) => {
    const idx = placeholders.length;
    placeholders.push(html);
    return `\u0000PH${idx}\u0000`;
  };

  let text = raw;

  // 1. Preserve HTML tables generated by normalizer
  text = text.replace(/<table class="exam-table">[\s\S]*?<\/table>/g, (m) => {
    // Render KaTeX inside table cells too
    const withMath = m
      .replace(/\$\$([\s\S]*?)\$\$/g, (_, eq) => renderKatexSafe(eq, true))
      .replace(/\$([^$]+?)\$/g, (_, eq) => renderKatexSafe(eq.replace(/\s*\n\s*/g, " "), false));
    return hold(withMath);
  });

  // 2. Preserve display math $$ ... $$
  text = text.replace(/\$\$([\s\S]*?)\$\$/g, (_, eq) => hold(`<div class="katex-block">${renderKatexSafe(eq, true)}</div>`));

  // 3. Preserve inline math $ ... $ (allow multiline $ ... $ from LaTeX \( ... \))
  text = text.replace(/\$([^$]+?)\$/g, (_, eq) => hold(renderKatexSafe(eq.replace(/\s*\n\s*/g, " "), false)));

  // 4. Preserve Markdown images ![alt](path)
  text = text.replace(/!\[([^\]]*)\]\(([^)]+)\)/g, (_, alt, src) => {
    const cleanSrc = src.startsWith("http") || src.startsWith("/") ? src : bankUrl(src);
    return hold(`<img src="${escapeHtml(cleanSrc)}" alt="${escapeHtml(alt || "配图")}" loading="lazy" />`);
  });

  // 5. Escape remaining text & apply basic Markdown (**bold**, paragraphs)
  text = escapeHtml(text);
  text = text.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");

  if (inline) {
    return text.replace(/\u0000PH(\d+)\u0000/g, (_, idx) => placeholders[Number(idx)] || "");
  }

  const blocks = text.split(/\n{2,}/);
  const htmlBlocks = blocks
    .map((blk) => blk.trim())
    .filter(Boolean)
    .map((blk) => {
      if (/^\u0000PH\d+\u0000$/.test(blk)) return blk;
      return `<p>${blk.replace(/\n/g, "<br/>")}</p>`;
    });

  let finalHtml = htmlBlocks.join("");
  finalHtml = finalHtml.replace(/\u0000PH(\d+)\u0000/g, (_, idx) => placeholders[Number(idx)] || "");
  return finalHtml;
}

export default function MathContent({ content, className = "", inline = false }) {
  const html = useMemo(() => renderContentToHtml(content, inline), [content, inline]);
  if (inline) {
    return <span className={className} dangerouslySetInnerHTML={{ __html: html }} />;
  }
  return <div className={`math-prose ${className}`} dangerouslySetInnerHTML={{ __html: html }} />;
}
